-- Company portal credentials are stored separately from the business profile.
-- The company profile itself remains in the existing company table.
CREATE TABLE IF NOT EXISTS company_auth_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    company_id INTEGER NOT NULL UNIQUE
        REFERENCES company(company_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_company_auth_accounts_company_id
    ON company_auth_accounts(company_id);
